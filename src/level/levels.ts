import { TILE } from "../config";

/**
 * Levels are authored as ASCII rows (row 0 = top of the world).
 *
 * Legend:
 *   .  empty
 *   #  solid ground
 *   I  ice (frictionless)
 *   ~  water (hazard, resets ball)
 *   r  rough (heavy grass, weak shots)
 *   F  checkpoint flag
 *   *  finish tile
 *   S  spawn
 *   /  slope, surface rising to the right
 *   \  slope, surface rising to the left
 */
export const CHAR_TO_TILE: Record<string, number> = {
  ".": TILE.EMPTY,
  "#": TILE.SOLID,
  I: TILE.ICE,
  "~": TILE.WATER,
  r: TILE.ROUGH,
  F: TILE.FLAG,
  "*": TILE.FINISH,
  S: TILE.SPAWN,
  "/": TILE.SLOPE_UP_RIGHT,
  "\\": TILE.SLOPE_UP_LEFT,
};

export interface RawLevel {
  title: string;
  creator: string;
  par: number;
  rows: string[];
}

